/** Returns the service with Arabic content merged in when locale is "ar". */
export function localizeService(service: Service, locale: string): Service {
  if (locale !== "ar") return service;
  const tr = serviceTranslationsAr[service.slug];
  if (!tr) return service;
  return {
    ...service,
    title: tr.title,
    shortTitle: tr.shortTitle,
    description: tr.description,
    shortDescription: tr.shortDescription,
    features: tr.features,
    process: service.process.map((p, i) => ({
      ...p,
      title: tr.process[i]?.title ?? p.title,
      description: tr.process[i]?.description ?? p.description,
    })),
    trailerTypes: service.trailerTypes?.map((tt, i) => ({
      ...tt,
      name: tr.trailerTypes?.[i]?.name ?? tt.name,
      description: tr.trailerTypes?.[i]?.description ?? tt.description,
    })),
  };
}
